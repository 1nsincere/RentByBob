 assert.match(await page.locator('.paid-rent-summary .simple-balance').innerText(),/3,000.00/)
 assert.equal(await page.locator('.paid-payment-list article').count(),1)
 await page.getByLabel('Payment month',{exact:true}).fill('2026-09')
 await page.getByRole('heading',{name:'No confirmed payments for this month'}).waitFor()
 await page.getByRole('button',{name:'Record and confirm'}).click()
 await page.getByRole('button',{name:'Record cash payment'}).click()
 await page.getByLabel('How much was received? (PHP)').fill('2500.25')
 await page.getByLabel('When was it received?').fill('2026-10-18')
 await page.getByRole('button',{name:'Review payment',exact:true}).click()
 await page.getByRole('button',{name:'Save pending record'}).click()
 await page.getByRole('button',{name:'Paid rent',exact:true}).click()
 await page.getByLabel('Payment month',{exact:true}).fill('2026-10')
 assert.match(await page.locator('.paid-rent-summary .simple-balance').innerText(),/3,000.00/)
