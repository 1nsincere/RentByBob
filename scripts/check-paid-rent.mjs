 await page.getByRole('button',{name:'Paid rent',exact:true}).click()
 assert.match(await page.locator('.paid-rent-summary .simple-balance').innerText(),/5,500.25/)
 assert.equal(await page.locator('.paid-payment-list article').count(),2)
 assert.match(await page.locator('.paid-payment-list').innerText(),/fully paid now/)
 assert.match(await page.locator('.paid-payment-list').innerText(),/4,499.75 still left/)
