import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'
const browser = await chromium.launch({ channel:'msedge', headless:true })
try {
 const page = await browser.newPage({viewport:{width:1440,height:1000}})
 const errors=[], external=[]
 page.on('pageerror', e=>errors.push(e.message))
 await page.route('**/*', route=>{ if(new URL(route.request().url()).origin !== 'http://127.0.0.1:5173'){external.push(route.request().url());return route.abort()}return route.continue() })
 await page.goto('http://127.0.0.1:5173/?preview=1')
 await page.locator('.workspace-sidebar').getByRole('link',{name:'Payments and balances'}).click()
 const balance=page.locator('.simple-balance strong')
 assert.match(await balance.innerText(),/7,000.00/)
 const pendingCard=page.locator('.pending-cash-card')
 assert.match(await pendingCard.innerText(),/Pending · not confirmed/)
 assert.match(await pendingCard.innerText(),/does not reduce the rent balance/)
 assert.match(await pendingCard.innerText(),/Collected by[\s\S]*Bob[\s\S]*Date received[\s\S]*Oct 10, 2026/)
 assert.ok(await page.locator('.pending-cash-row > .button').evaluate(button=>button.getBoundingClientRect().height>=44),'pending review action should remain a comfortable touch target')
 await page.getByText('Rent by month',{exact:true}).click()
 const rentRows=page.locator('.rent-month-row')
 assert.equal(await rentRows.count(),2)
 assert.match(await rentRows.nth(0).innerText(),/September 2026[\s\S]*Due date[\s\S]*Rent charged[\s\S]*₱5,000\.00[\s\S]*Still to pay[\s\S]*₱2,000\.00/)
 assert.match(await rentRows.nth(1).innerText(),/October 2026[\s\S]*Due date[\s\S]*Rent charged[\s\S]*₱5,000\.00[\s\S]*Still to pay[\s\S]*₱5,000\.00/)
 assert.match(await page.locator('.room-total-note').innerText(),/Combined room balance · all accounts[\s\S]*₱7,000\.00[\s\S]*not an extra charge/)
 await page.getByText('Payment history',{exact:true}).click()
 const history=page.locator('.payment-history-row')
 assert.equal(await history.count(),2)
 assert.match(await history.nth(0).innerText(),/Pending · not confirmed[\s\S]*₱1,000\.00[\s\S]*Date received[\s\S]*Oct 10, 2026[\s\S]*Received by[\s\S]*Bob/)
 assert.match(await history.nth(1).innerText(),/Confirmed example payment[\s\S]*₱3,000\.00[\s\S]*Date received[\s\S]*Oct 2, 2026/)
 await page.getByText('Payment history',{exact:true}).click()
 await page.getByText('Room rent setup',{exact:true}).click()
 assert.equal(await page.getByLabel('Move-in date').getAttribute('readonly'), '')
 assert.equal(await page.getByLabel('Room rent (PHP)').getAttribute('readonly'), '')
 assert.equal(await page.locator('.fixed-field-badge').count(),2)
 await page.getByLabel('Change room rent').check()
 await page.getByLabel('Room rent (PHP)').fill('5500.00')
 await page.getByLabel('Change room rent').uncheck()
 assert.equal(await page.getByLabel('Room rent (PHP)').inputValue(),'5000.00','locking the rent again should discard the uncommitted draft')
 assert.equal(await page.getByLabel('Room rent (PHP)').getAttribute('readonly'),'')
 await page.getByLabel('Change room rent').check()
 await page.getByLabel('Room rent (PHP)').fill('5500.00')
 await page.getByRole('button',{name:'Record cash payment'}).click()
 await page.getByLabel('How much was received? (PHP)').fill('2500.25')
 await page.getByRole('button',{name:'Review payment',exact:true}).click()
 assert.match(await page.locator('.payment-review').innerText(),/September 2026/)
 assert.match(await page.locator('.payment-review').innerText(),/October 2026/)
 await page.getByRole('button',{name:'Save pending record'}).click()
 assert.match(await balance.innerText(),/7,000.00/)
 await page.getByRole('button',{name:'Review cash',exact:true}).last().click()
 await page.getByRole('button',{name:'Confirm as James (preview)'}).click()
 assert.match(await balance.innerText(),/4,499.75/)
 await page.getByRole('button',{name:'Review cash',exact:true}).click()
 assert.doesNotMatch(await page.locator('.payment-review').innerText(),/September 2026/)
 await page.getByRole('button',{name:'Confirm as James (preview)'}).click()
 assert.match(await balance.innerText(),/3,499.75/)
 await page.getByLabel('Month to add').fill('2026-11')
 await page.getByRole('button',{name:"Add this month's rent"}).click()
 const rentReview=page.locator('.rent-change-review')
 assert.match(await rentReview.innerText(),/Current room rent[\s\S]*₱5,000\.00[\s\S]*New room rent[\s\S]*₱5,500\.00[\s\S]*November 2026[\s\S]*Due date[\s\S]*Nov 1, 2026/)
 assert.match(await rentReview.innerText(),/Existing recorded charges stay unchanged/)
 assert.equal(await page.locator('.rent-month-row').count(),2,'rent change review must not add a charge before confirmation')
 assert.match(await balance.innerText(),/3,499.75/,'rent change review must not alter balance before confirmation')
 await page.getByRole('button',{name:'Edit details',exact:true}).click()
 assert.equal(await page.locator('.rent-change-review').count(),0)
 assert.equal(await page.getByLabel('Room rent (PHP)').inputValue(),'5500.00','returning to edit details should preserve the draft for correction/review')
 await page.getByRole('button',{name:"Add this month's rent"}).click()
 await page.getByRole('button',{name:'Confirm rent change and add month'}).click()
 assert.equal(await page.locator('.rent-month-row').count(),3)
 assert.match(await page.locator('.rent-month-row').nth(0).innerText(),/September 2026[\s\S]*₱5,000\.00/)
 assert.match(await page.locator('.rent-month-row').nth(1).innerText(),/October 2026[\s\S]*₱5,000\.00/)
 assert.match(await page.locator('.rent-month-row').nth(2).innerText(),/November 2026[\s\S]*₱5,500\.00/)
 assert.equal(await page.getByLabel('Room rent (PHP)').getAttribute('readonly'), '')
 assert.equal(await page.getByLabel('Room rent (PHP)').inputValue(),'5500.00')
 assert.match(await balance.innerText(),/8,999.75/)
 await page.getByLabel('Month to add').fill('2026-11')
 await page.getByRole('button',{name:"Add this month's rent"}).click()
 assert.match(await page.getByRole('alert').innerText(),/already recorded/)
 assert.equal(await page.locator('.rent-month-row').count(),3,'a duplicate room/month charge must not be added')
 assert.match(await balance.innerText(),/8,999.75/,'a duplicate month must not alter the balance')
 await page.evaluate(()=>scrollTo(0,0))
 await page.screenshot({path:'docs/screenshots/payments-simple.png',fullPage:true})
 for(const width of [320,390,768]){
  await page.setViewportSize({width,height:900})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  const rowWidths=await page.locator('.rent-month-row').evaluateAll(rows=>rows.map(row=>row.getBoundingClientRect().width))
  assert.ok(rowWidths.every(width=>width>0),'rent month rows should remain visible after workflow transitions')
 }
 await page.setViewportSize({width:390,height:900})
 await page.screenshot({path:'docs/screenshots/payments-simple-mobile.png',fullPage:true})
 assert.deepEqual(errors,[]);assert.deepEqual(external,[])
 console.log('PASS: pending does not settle; oldest-first split; confirmation reallocation; narrow reflow; no external requests/errors')
}finally{await browser.close()}
