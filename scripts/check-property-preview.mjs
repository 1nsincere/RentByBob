import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const requests = []
  await page.route('**/*', route => {
    if (new URL(route.request().url()).origin !== 'http://127.0.0.1:5175') { requests.push(route.request().url()); return route.abort() }
    return route.continue()
  })
  await page.goto('http://127.0.0.1:5175')
  await page.getByRole('heading', { name: 'Sample Alex Santos', exact: true }).waitFor()
  assert.equal(await page.locator('.tenant-person-card').count(), 3)
  await page.locator('.tenant-person-card').first().getByRole('button', { name: 'View details' }).click()
  await page.getByText('alex@example.invalid', { exact: true }).waitFor()
  await page.locator('.tenant-person-card').first().getByRole('button', { name: 'Locate room' }).click()
  await page.locator('.room-editor').getByRole('heading', { name: 'Room 01', exact: true }).waitFor()
  assert.equal(await page.locator('.room-tile').count(), 6)
  await page.getByLabel('Room or space label').fill('Garden Room')
  await page.getByRole('button', { name: 'Rename space', exact: true }).click()
  await page.getByLabel('Rental rooms', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Update preview layout' }).click()
  await page.getByText('Keep occupied example rooms.', { exact: false }).waitFor()
  assert.equal(await page.locator('.room-tile').count(), 6)
  await page.getByRole('button', { name: 'Explore Building 1', exact: true }).click()
  await page.getByLabel('Rental rooms', { exact: true }).fill('4')
  await page.getByRole('button', { name: 'Update preview layout' }).click()
  assert.equal(await page.locator('.room-tile').count(), 5)
  await page.locator('.room-tile').filter({ hasText: 'Apartment' }).waitFor()
  await page.getByRole('button', { name: 'Second floor', exact: true }).click()
  await page.getByLabel('Rental rooms', { exact: true }).fill('7')
  await page.getByRole('button', { name: 'Update preview layout' }).click()
  assert.equal(await page.locator('.room-tile').count(), 7)
  await page.getByRole('button', { name: 'Explore Building 2', exact: true }).click()
  await page.locator('.room-tile').filter({ hasText: 'Gym' }).waitFor()
  await page.getByRole('button', { name: 'Explore Bob\'s house', exact: true }).click()
  await page.locator('.property-visual').screenshot({ path: 'docs/screenshots/property-map-preview.png' })
  await page.getByRole('button', { name: '+ Add building', exact: true }).click()
  await page.getByLabel('Building name', { exact: true }).first().fill('Sample Annex')
  await page.getByLabel('Number of floors').fill('3')
  await page.getByRole('button', { name: 'Add to preview', exact: true }).click()
  await page.getByRole('heading', { name: 'Sample Annex', exact: true }).waitFor()
  assert.equal(await page.locator('.floor-tabs button').count(), 3)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Building list', exact: true }).click()
  await page.getByRole('button', { name: "Bob's house 1 level", exact: true }).click()
  await page.locator('.property-visual').screenshot({ path: 'docs/screenshots/property-mobile-preview.png' })
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 900 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Page overflow at ${width}`)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('link', { name: 'Tenant directory', exact: true }).click()
  await page.getByText('Rooms for rent · Garden Room', { exact: true }).waitFor()
  await page.locator('.visual-directory').screenshot({ path: 'docs/screenshots/tenant-cards-preview.png' })
  await page.getByLabel('Tenant status', { exact: true }).selectOption('archived')
  assert.equal(await page.locator('.tenant-person-card').count(), 1)
  assert.deepEqual(requests, [])
  console.log('PASS: active cards, details/location, room rename, occupied-room protection, separate floor counts, apartment/gym preservation, add building, mobile list/reflow, shared directory updates and zero backend calls.')
} finally { await browser.close() }
