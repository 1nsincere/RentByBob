import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'
import { screenshotDir } from './screenshot-dir.mjs'
const browser=await chromium.launch({channel:'msedge',headless:true})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 const errors=[], external=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/*',route=>{if(new URL(route.request().url()).origin!=='http://127.0.0.1:5173'){external.push(route.request().url());return route.abort()} return route.continue()})
 await page.goto('http://127.0.0.1:5173/?preview=1')
 await page.getByRole('button',{name:/Find a tenant/}).click()
 await page.locator('.tenant-person-card').filter({hasText:'Sample Mara Reyes'}).getByRole('button',{name:'View rent and payments'}).click()
 assert.equal(await page.getByLabel('1. Choose tenant').inputValue(),'mara')
 await page.getByLabel('Show',{exact:true}).selectOption('unpaid')
 assert.equal(await page.locator('.payment-overview article').count(),2)
 await page.getByLabel('Find tenant or room').fill('Room 01')
 assert.equal(await page.locator('.payment-overview article').count(),1)
 await page.getByRole('button',{name:'Open payments for Sample Alex Santos'}).click()
 assert.equal(await page.getByLabel('1. Choose tenant').inputValue(),'alex')
 await page.getByRole('button',{name:'Record cash payment'}).click()
 await page.getByLabel('How much was received? (PHP)').fill('1000')
 await page.getByLabel('When was it received?').fill('2026-10-10')
 await page.getByRole('button',{name:'Review payment',exact:true}).click()
 assert.equal(await page.getByRole('button',{name:'Save pending record'}).isDisabled(),true)
 await page.locator('.duplicate-warning input').check()
 await page.getByRole('button',{name:'Save pending record'}).click()
 assert.match(await page.locator('#payment-tenant').locator('xpath=..').locator('.simple-balance strong').innerText(),/7,000.00/)
 await page.getByLabel('Find tenant or room').fill('')
 await page.getByLabel('Show',{exact:true}).selectOption('pending')
 assert.match(await page.locator('.payment-overview').innerText(),/2 cash records are waiting for James/)
 await page.evaluate(()=>scrollTo(0,0))
 await page.screenshot({path:`${screenshotDir}/admin-worklist.png`,fullPage:true})
 for(const width of [320,390,768]){await page.setViewportSize({width,height:900});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'overflow '+width)}
 await page.setViewportSize({width:390,height:900})
 await page.screenshot({path:`${screenshotDir}/admin-worklist-mobile.png`,fullPage:true})
 await page.setViewportSize({width:768,height:900})
 await page.evaluate(()=>document.documentElement.style.fontSize='225%')
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 await page.setViewportSize({width:320,height:900})
 await page.evaluate(()=>document.documentElement.style.fontSize='200%')
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'overflow at 200% text zoom equivalent')
 assert.ok(await page.locator('button').evaluateAll(buttons=>buttons.filter(button=>button.getClientRects().length>0).every(button=>button.getBoundingClientRect().height>=44)),'visible button target below 44px at 200% text size')
 assert.deepEqual(errors,[]);assert.deepEqual(external,[])
 console.log('PASS: tenant-to-payment navigation; unpaid/search/pending worklist; duplicate review; pending balance unchanged; reflow and enlarged text; no external requests/errors')
}finally{await browser.close()}
